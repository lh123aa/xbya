"""繁→简归一化（**只用于匹配，不改变用户可见文本**）

## 为什么需要它

ASR（faster_whisper）对中文**经常输出繁体** —— 实测「删除桌面上的截图」被转写成
「删除桌面上的**截圖**。」（前两个字简体、后两个字繁体，混着来）。
而规则路由的关键词表全是简体，于是：

    意图认得出来（"删除"匹配上了）
    文件类型不认得（"截圖" 不在 EXT_ALIASES 里）
    → params 里没有 pattern，而**置信度仍是 0.95，没被阈值拦下**
    → 管线用实体栈兜底补目标
    → "删除截图" 变成了 "删除上一次搜索到的文件"

这是**静默做错事**，比明确拒绝危险得多（直接关系 R1）。修法就是在匹配前把繁体归一成简体。

## 为什么是"词级 + 无歧义字级"，而不是纯字级

一开始为了躲歧义只做了**词级**。但验收阶段用
`python tools/measure_asr_stimulus.py --synth 6` 一测就露了：
ASR 输出「給我講個笑話」，词表里有 `給我`、没有 `講個`/`笑話`
→ 归一化后仍是「给我講個笑話」，**关键词照样漏**。

再逐条核对规则路由的真实词表，发现漏的远不止一句：`內存`/`電池`/`硬盤`/
`氣溫`/`啟動`/`減去`/`等於`/`訪問`/`粘貼`/`多少電` …… 全是**路由关键词**
（`system_info` 的「内存」「电池」「硬盘」、「weather」的「气温」…），
它们的繁体写法归一化不了 → 与缺陷 14 完全同一类失败（静默丢参数）。

所以补了一层**字级**表。它安全的原因是**方向**：
繁→简是**多对一**，把 `圖` 换成 `图` 不会产生歧义；歧义只存在于
"简体 → 繁体"方向（`干` 到底是 `乾` 还是 `幹`）。
唯一要小心的是少数**繁体字本身多义**的：`乾`（乾坤/乾燥）、`徵`（宫商角徵羽），
这两个**故意不收**（`T2S_AMBIGUOUS_TRAD`，有测试钉住）。

## 边界（有意为之）

- **不是通用繁简转换器**（那需要 OpenCC 或一张几千字的表 → 新依赖）。
  没命中就原样保留，行为与加这个模块之前**完全一致**，所以不存在"改坏了"的回退风险。
- **只作用于匹配文本**：`RuleRouter._normalize()` 的返回值用于查词表与提取参数，
  而 `AgentCommand.raw_text` 始终保存**用户原话**，播报/气泡不受影响。
- **权衡**：若用户的文件**真的**以繁体命名（如 `截圖_01.png`），
  归一化后的 `*截图*` 会匹配不到它。现实里 ASR 输出繁体、文件名却是简体是绝对多数，
  故取此权衡；真要两边都覆盖，得给工具加"多模式"支持（未做，记在文档里）。
"""

